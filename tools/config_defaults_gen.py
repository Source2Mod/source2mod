"""Turns the core's shipped *.example.json files into config_defaults_gen.h.

The same files are the defaults the core registers its configs with
(core/configs.h) and the examples in the release, so the two cannot drift
apart. Each file becomes a string constant k<Name>ConfigDefaults, written as
short escaped literals (MSVC caps a single literal at 16 KB).
"""
import argparse
import pathlib


def literal(data: bytes) -> str:
    out = []
    for b in data:
        c = chr(b)
        if c == '\\':
            out.append('\\\\')
        elif c == '"':
            out.append('\\"')
        elif c == '\n':
            out.append('\\n')
        elif c == '\r':
            out.append('\\r')
        elif c == '\t':
            out.append('\\t')
        elif 0x20 <= b < 0x7f and c != '?':
            out.append(c)
        else:
            # Octal, always three digits: a hex escape would swallow the
            # characters after it.
            out.append('\\%03o' % b)
    # One literal per source line (escapes are whole tokens, so a break
    # never lands inside one).
    chunks, current = [], ''
    for token in out:
        current += token
        if token == '\\n' or len(current) >= 1000:
            chunks.append(current)
            current = ''
    if current or not chunks:
        chunks.append(current)
    return '\n'.join('    "%s"' % c for c in chunks)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True)
    parser.add_argument('files', nargs='+', help='Name=path')
    args = parser.parse_args()

    lines = ['// Generated by tools/config_defaults_gen.py from configs/*.example.json. Do not edit.',
             '#pragma once', '']
    for item in args.files:
        name, path = item.split('=', 1)
        data = pathlib.Path(path).read_bytes()
        lines.append('inline constexpr const char k%sConfigDefaults[] =' % name)
        lines.append(literal(data) + ';')
        lines.append('')

    out = pathlib.Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    if not out.exists() or out.read_text(encoding='utf-8') != text:
        out.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
